/// Single-byte encoder for the Windows-1256 (Arabic) code page.
///
/// Thermal ESC/POS printers do not consume UTF-8 directly. To print Arabic
/// glyphs the firmware needs:
///
///   1. A code page that contains Arabic letters (CP1256 / WPC1256), and
///   2. Bytes encoded against that code page.
///
/// Code 0x00..0x7F is identical to ASCII (so English mixed inside an Arabic
/// run prints fine). The 0x80..0xFF map below mirrors the Microsoft CP1256
/// definition (covers Arabic letters, harakat, punctuation, Latin-1 fallback
/// characters). Codepoints with no mapping fall back to `?` (0x3F).
class Cp1256Encoder {
  Cp1256Encoder._();

  /// Returns true when `cp` is part of the Arabic Unicode blocks
  /// (base + supplement + presentation forms).
  static bool isArabicChar(int cp) {
    return (cp >= 0x0600 && cp <= 0x06FF) ||
        (cp >= 0x0750 && cp <= 0x077F) ||
        (cp >= 0x08A0 && cp <= 0x08FF) ||
        (cp >= 0xFB50 && cp <= 0xFDFF) ||
        (cp >= 0xFE70 && cp <= 0xFEFF);
  }

  /// True when any rune of [text] is Arabic.
  static bool containsArabic(String text) => text.runes.any(isArabicChar);

  /// Encodes [text] into a CP1256 byte stream. Unmapped codepoints become
  /// `?` (0x3F) so the printer still prints something predictable.
  static List<int> encode(String text) {
    final out = <int>[];
    for (final cp in text.runes) {
      if (cp < 0x80) {
        out.add(cp);
        continue;
      }
      final mapped = _map[cp];
      out.add(mapped ?? 0x3F);
    }
    return out;
  }

